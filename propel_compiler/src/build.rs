//! A build-script helper that compiles a views folder into Rust.
//!
//! ```ignore
//! // build.rs of the app
//! fn main() {
//!     propel_compiler::build::Views::new("resources/views")
//!         .namespace("ignite", "vendor/ignite/resources/views")
//!         .view("posts.index", "crate::posts::IndexContext")
//!         .build();
//! }
//! ```
//!
//! The app then includes the generated module:
//!
//! ```ignore
//! include!(concat!(env!("OUT_DIR"), "/propel_views.rs"));
//! // posts::index::render(&ctx, &assets) -> Result<String, RenderError>
//! ```
//!
//! Every template under the root and each namespace is parsed, so a syntax
//! error stops the build even in a view that nothing uses yet. Each view named
//! with `view` is compiled in full, with its layouts, partials and sections.
//! `build` prints the error and exits the build script when a template is wrong.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use propel_runtime::{FileLoader, Loader};

use crate::codegen::KEYWORDS;
use crate::{generate, CompileError, Options, Templates};

/// The file in `OUT_DIR` that holds the generated module.
pub const OUTPUT_FILE: &str = "propel_views.rs";

/// Builds the views of one app. See the module docs.
#[derive(Debug, Clone, Default)]
pub struct Views {
    root: PathBuf,
    namespaces: Vec<(String, PathBuf)>,
    entries: Vec<(String, String)>,
    runtime_path: Option<String>,
    base: Option<PathBuf>,
}

impl Views {
    /// Views are read from `root`, such as `resources/views`.
    pub fn new(root: impl Into<PathBuf>) -> Self {
        Self {
            root: root.into(),
            ..Self::default()
        }
    }

    /// A namespace, as `ignite::index`. Its views come from `root`.
    pub fn namespace(mut self, name: impl Into<String>, root: impl Into<PathBuf>) -> Self {
        self.namespaces.push((name.into(), root.into()));
        self
    }

    /// A view the app renders, with the Rust type of its context. Only these
    /// views get a `render` function. Layouts and partials are compiled into
    /// the views that use them.
    pub fn view(mut self, name: impl Into<String>, context_type: impl Into<String>) -> Self {
        self.entries.push((name.into(), context_type.into()));
        self
    }

    /// The directory that template paths in error messages are shown relative
    /// to. Proc macros set it to the crate's manifest directory, so an absolute
    /// root still gives short paths. By default paths are shown as they are.
    pub fn relative_to(mut self, base: impl Into<PathBuf>) -> Self {
        self.base = Some(base.into());
        self
    }

    /// The path to `propel_runtime` in the generated code, when the app does
    /// not depend on it directly. The default is `::propel_runtime`.
    pub fn runtime_path(mut self, path: impl Into<String>) -> Self {
        self.runtime_path = Some(path.into());
        self
    }

    /// The Rust source of the generated module. It parses every template and
    /// compiles every view, and returns the first error it finds.
    pub fn generate(&self) -> Result<String, CompileError> {
        let templates = FileTemplates::new(self);

        for (name, path) in self.template_files() {
            let source = fs::read_to_string(&path).map_err(|error| CompileError {
                template: name.clone(),
                message: format!("could not read `{}`: {error}", path.display()),
            })?;
            propel_parser::parse(&source).map_err(|error| CompileError {
                template: name.clone(),
                message: format!("could not parse `{}`:\n{error}", path.display()),
            })?;
        }

        let mut tree = Tree::default();
        for (view, context_type) in &self.entries {
            let mut options = Options::new(context_type.clone());
            if let Some(runtime) = &self.runtime_path {
                options.runtime_path = runtime.clone();
            }
            let function = generate(&templates, view, &options)?;
            let path = module_path(view).map_err(|message| CompileError {
                template: view.clone(),
                message,
            })?;
            tree.insert(&path, function)
                .map_err(|message| CompileError {
                    template: view.clone(),
                    message,
                })?;
        }

        let mut out = String::from("// Generated by propel_compiler. Do not edit.\n");
        tree.render(&mut out);
        Ok(out)
    }

    /// The context fields that `view` reads, with their template positions.
    /// The `PropelContext` derive checks them against the struct.
    pub fn references(&self, view: &str) -> Result<Vec<crate::Reference>, CompileError> {
        crate::references(&FileTemplates::new(self), view)
    }

    /// For a build script. Writes the module to `OUT_DIR/propel_views.rs` and
    /// tells Cargo which files to watch. A template error is printed and the
    /// build script exits with status 1, so the build fails at that template.
    pub fn build(&self) {
        for (_, path) in self.template_files() {
            println!("cargo:rerun-if-changed={}", path.display());
        }
        println!("cargo:rerun-if-changed={}", self.root.display());
        for (_, root) in &self.namespaces {
            println!("cargo:rerun-if-changed={}", root.display());
        }

        let module = match self.generate() {
            Ok(module) => module,
            Err(error) => {
                eprintln!("error: propel: {error}");
                std::process::exit(1);
            }
        };

        let Some(out_dir) = std::env::var_os("OUT_DIR") else {
            eprintln!("error: propel: OUT_DIR is not set; call Views::build from build.rs");
            std::process::exit(1);
        };
        let target = Path::new(&out_dir).join(OUTPUT_FILE);
        if let Err(error) = fs::write(&target, module) {
            eprintln!(
                "error: propel: could not write `{}`: {error}",
                target.display()
            );
            std::process::exit(1);
        }
    }

    /// Every `.propel` file under the root and under each namespace, with its
    /// template name (`posts.index`, or `ignite::index` in a namespace).
    fn template_files(&self) -> Vec<(String, PathBuf)> {
        let mut files = Vec::new();
        collect_files(&self.root, "", &mut files);
        for (namespace, root) in &self.namespaces {
            collect_files(root, &format!("{namespace}::"), &mut files);
        }
        files
    }
}

/// Lists `.propel` files under `dir`, in name order, with `prefix` added to
/// each template name.
fn collect_files(dir: &Path, prefix: &str, files: &mut Vec<(String, PathBuf)>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    let mut paths: Vec<PathBuf> = entries.filter_map(|e| e.ok().map(|e| e.path())).collect();
    paths.sort();

    for path in paths {
        if path.is_dir() {
            collect_files(&path, &format!("{prefix}{}.", file_stem(&path)), files);
        } else if path.extension().is_some_and(|ext| ext == "propel") {
            files.push((format!("{prefix}{}", file_stem(&path)), path));
        }
    }
}

fn file_stem(path: &Path) -> String {
    path.file_stem()
        .map(|stem| stem.to_string_lossy().into_owned())
        .unwrap_or_default()
}

/// Reads templates from the views folder and namespaces, with the same name
/// rules as the dev renderer.
struct FileTemplates {
    loader: FileLoader,
    root: PathBuf,
    namespaces: Vec<(String, PathBuf)>,
    base: Option<PathBuf>,
}

impl FileTemplates {
    fn new(views: &Views) -> Self {
        let loader = views
            .namespaces
            .iter()
            .fold(FileLoader::new(&views.root), |loader, (name, root)| {
                loader.namespace(name.clone(), root.clone())
            });
        Self {
            loader,
            root: views.root.clone(),
            namespaces: views.namespaces.clone(),
            base: views.base.clone(),
        }
    }
}

impl Templates for FileTemplates {
    fn template(&self, name: &str) -> Result<propel_parser::Template, String> {
        let source = self
            .loader
            .source(name)
            .map_err(|error| format!("could not read template `{name}`: {error}"))?;
        propel_parser::parse(&source).map_err(|error| format!("could not parse `{name}`:\n{error}"))
    }

    fn path(&self, name: &str) -> String {
        let (root, view) = match name.split_once("::") {
            Some((namespace, view)) => {
                let root = self
                    .namespaces
                    .iter()
                    .find(|(known, _)| known == namespace)
                    .map_or_else(|| self.root.clone(), |(_, root)| root.clone());
                (root, view)
            }
            None => (self.root.clone(), name),
        };
        let mut path = root;
        for segment in view.split('.') {
            path.push(segment);
        }
        let path = path.with_extension("propel");
        let shown = match &self.base {
            Some(base) => path
                .strip_prefix(base)
                .map(Path::to_path_buf)
                .unwrap_or(path),
            None => path,
        };
        shown.display().to_string()
    }
}

/// `posts.index` becomes `["posts", "index"]`, and `ignite::index` becomes
/// `["ignite", "index"]`. A hyphen becomes an underscore, since it cannot be
/// in a Rust name.
pub(crate) fn module_path(view: &str) -> Result<Vec<String>, String> {
    let dotted = view.replace("::", ".");
    dotted
        .split('.')
        .map(|segment| {
            let ident = segment.replace('-', "_");
            if ident.is_empty() {
                return Err(format!("invalid view name `{view}`"));
            }
            if matches!(ident.as_str(), "self" | "super" | "crate" | "Self" | "_") {
                return Err(format!("`{view}` cannot be a module name"));
            }
            Ok(ident)
        })
        .collect()
}

/// The modules and functions of the generated file.
#[derive(Default)]
struct Tree {
    children: BTreeMap<String, Tree>,
    body: Option<String>,
}

impl Tree {
    fn insert(&mut self, path: &[String], body: String) -> Result<(), String> {
        let mut node = self;
        for segment in path {
            node = node.children.entry(segment.clone()).or_default();
        }
        if node.body.is_some() {
            return Err(format!("two views map to the module `{}`", path.join("::")));
        }
        node.body = Some(body);
        Ok(())
    }

    fn render(&self, out: &mut String) {
        for (name, child) in &self.children {
            let ident = if KEYWORDS.contains(&name.as_str()) {
                format!("r#{name}")
            } else {
                name.clone()
            };
            out.push_str(&format!("pub mod {ident} {{\n"));
            if let Some(body) = &child.body {
                out.push_str(body);
            }
            child.render(out);
            out.push_str("}\n");
        }
    }
}
